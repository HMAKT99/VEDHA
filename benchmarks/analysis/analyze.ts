import fs from "node:fs";
import path from "node:path";
import { isCorrect, isFalsePass, type TrialRecord } from "../harness/classify.js";
import { ci, mean, median, percentile, signTest, wilson } from "./stats.js";

const runDir = path.resolve(process.argv[2] ?? "benchmarks/results/main-n20");
const trials: TrialRecord[] = fs
  .readFileSync(path.join(runDir, "trials.jsonl"), "utf8")
  .trim()
  .split("\n")
  .map((l) => JSON.parse(l) as TrialRecord);
const env = JSON.parse(fs.readFileSync(path.join(runDir, "env.json"), "utf8")) as Record<
  string,
  unknown
>;

const drivers = [...new Set(trials.map((t) => t.driver))];
const order = ["pw-trust", "pw-test", "pw-strong", "pw-heal-naive", "vedha"];
drivers.sort((a, b) => order.indexOf(a) - order.indexOf(b));
const scenarios = [...new Set(trials.map((t) => t.scenario))].sort();
const kindOf = (s: string) => trials.find((t) => t.scenario === s)!.kind;

const cell = (s: string, d: string) => trials.filter((t) => t.scenario === s && t.driver === d);
const rate = (xs: TrialRecord[], f: (t: TrialRecord) => boolean) => xs.filter(f).length;

const lines: string[] = [];
const P = (s = "") => lines.push(s);

P(`# Benchmark results: ${path.basename(runDir)}`);
P();
P(
  `Generated by \`benchmarks/analysis/analyze.ts\` from \`${path.relative(process.cwd(), runDir)}/trials.jsonl\`. Raw per-trial records are the source of truth.`,
);
P();
P(
  `* Trials: ${trials.length} (${scenarios.length} scenarios × ${drivers.length} drivers × ${env.trials} trials). Driver errors (harness-level): ${trials.filter((t) => t.outcome === "driver_error").length}.`,
);
P(
  `* Environment: ${String(env.platform)}, ${String(env.cpus)} CPUs (${String(env.cpuModel)}), Node ${String(env.node)}, Playwright ${String(env.playwright)}, concurrency ${String(env.concurrency)}.`,
);
P(
  `* git HEAD at run time: \`${String(env.gitHead)}\`, working tree dirty: ${String(env.gitDirty)}.`,
);
P(
  `* **All actors are scripted (no LLM).** Results measure framework semantics (verification, recovery, uncertainty handling), not model capability. See \`methodology.md\`.`,
);
P(
  `* Intervals are 95% Wilson score intervals. With n=${env.trials} per cell, intervals are wide; a 20/20 cell has a lower bound of ~84%.`,
);
P();

P(`## 1. Correct outcome rate by scenario (task done and reported, or seeded defect reported)`);
P();
P(
  `"Correct" = outcome \`success\` (effect achieved and reported as pass) for effect scenarios, \`detected\` (reported fail) for defect scenarios. \`uncertain\` claims are never correct.`,
);
P();
P(`| scenario | kind | ${drivers.join(" | ")} |`);
P(`|---|---|${drivers.map(() => "---").join("|")}|`);
for (const s of scenarios) {
  P(
    `| ${s} | ${kindOf(s)} | ${drivers
      .map((d) => {
        const c = cell(s, d);
        return ci(
          rate(c, (t) => isCorrect(t.outcome)),
          c.length,
        );
      })
      .join(" | ")} |`,
  );
}
P();

P(
  `## 2. Costly errors: false passes (reported pass while the effect is absent or a seeded defect exists)`,
);
P();
P(`| scenario | kind | ${drivers.join(" | ")} |`);
P(`|---|---|${drivers.map(() => "---").join("|")}|`);
for (const s of scenarios) {
  P(
    `| ${s} | ${kindOf(s)} | ${drivers
      .map((d) => {
        const c = cell(s, d);
        return `${rate(c, (t) => isFalsePass(t.outcome))}/${c.length}`;
      })
      .join(" | ")} |`,
  );
}
P();
P(`Per driver, over all scenarios of each kind (kinds are not combined):`);
P();
P(
  `| driver | defect scenarios: missed (false pass) | effect scenarios: false pass | effect scenarios: false fail | effect scenarios: reported fail, no effect | uncertain claims | duplicates (extra side effects, mean per trial) | masked defects (pass after recovery on a defect) |`,
);
P(`|---|---|---|---|---|---|---|---|`);
for (const d of drivers) {
  const all = trials.filter((t) => t.driver === d);
  const def = all.filter((t) => t.kind === "defect");
  const eff = all.filter((t) => t.kind === "effect");
  P(
    `| ${d} | ${ci(
      rate(def, (t) => t.outcome === "missed"),
      def.length,
    )} | ${ci(
      rate(eff, (t) => t.outcome === "false_pass"),
      eff.length,
    )} | ${ci(
      rate(eff, (t) => t.outcome === "false_fail"),
      eff.length,
    )} | ${ci(
      rate(eff, (t) => t.outcome === "honest_fail"),
      eff.length,
    )} | ${rate(all, (t) => t.claim === "uncertain")}/${all.length} | ${mean(all.map((t) => t.duplicates)).toFixed(2)} | ${rate(def, (t) => t.maskedDefect)}/${def.length} |`,
  );
}
P();

P(
  `## 3. Latency (ms, wall clock per trial, includes waiting and retries; browser already launched) and actions`,
);
P();
P(`| scenario | ${drivers.map((d) => `${d} med / p95 / actions`).join(" | ")} |`);
P(`|---|${drivers.map(() => "---").join("|")}|`);
for (const s of scenarios) {
  P(
    `| ${s} | ${drivers
      .map((d) => {
        const c = cell(s, d);
        const l = c.map((t) => t.latencyMs).sort((a, b) => a - b);
        return `${Math.round(median(l))} / ${Math.round(percentile(l, 0.95))} / ${mean(c.map((t) => t.browserActions)).toFixed(1)}`;
      })
      .join(" | ")} |`,
  );
}
P();
P(
  `Latency differences between drivers in failing scenarios mostly reflect each driver's timeout/retry policy (e.g. waiting out a 5 s action timeout), not browser speed. Do not read them as speed claims.`,
);
P();

P(`## 4. Paired comparison: vedha vs each baseline (same scenario, same trial seed)`);
P();
P(
  `b = trials where vedha was correct and the baseline was not; c = the reverse. p = exact two-sided sign test on (b, c). Pairs are trial-index matched; with deterministic fixtures most pairs are concordant, so n of discordant pairs is small. No multiple-comparison correction is applied; treat p-values as descriptive.`,
);
P();
P(`| scenario | baseline | b (AF only correct) | c (baseline only correct) | p |`);
P(`|---|---|---|---|---|`);
const af = "vedha";
for (const s of scenarios) {
  for (const d of drivers.filter((x) => x !== af)) {
    let b = 0,
      c = 0;
    for (const t of cell(s, af)) {
      const o = cell(s, d).find((x) => x.trial === t.trial);
      if (!o) continue;
      const ac = isCorrect(t.outcome),
        oc = isCorrect(o.outcome);
      if (ac && !oc) b++;
      if (!ac && oc) c++;
    }
    if (b + c > 0) P(`| ${s} | ${d} | ${b} | ${c} | ${signTest(b, c).toFixed(4)} |`);
  }
}
P();
P(`Rows with no discordant pairs are omitted (the drivers behaved identically).`);
P();

P(`## 5. Recoveries and notes`);
P();
P(
  `| scenario | driver | trials with recovery | passed on retry/with recovery | example diagnostic |`,
);
P(`|---|---|---|---|---|`);
for (const s of scenarios) {
  for (const d of drivers) {
    const c = cell(s, d);
    const withRec = c.filter((t) => t.recoveries > 0 || t.notes);
    if (!withRec.length) continue;
    const ex = (c.find((t) => t.diagnostic)?.diagnostic ?? "").replace(/\|/g, "\\|").slice(0, 110);
    P(
      `| ${s} | ${d} | ${withRec.length}/${c.length} | ${rate(c, (t) => !!t.notes)}/${c.length} | ${ex} |`,
    );
  }
}
P();

const md = lines.join("\n") + "\n";
fs.writeFileSync(path.join(runDir, "results.md"), md);
const summary = Object.fromEntries(
  drivers.map((d) => [
    d,
    Object.fromEntries(
      scenarios.map((s) => {
        const c = cell(s, d);
        const k = rate(c, (t) => isCorrect(t.outcome));
        const [lo, hi] = wilson(k, c.length);
        return [
          s,
          {
            n: c.length,
            correct: k,
            wilsonLo: lo,
            wilsonHi: hi,
            falsePass: rate(c, (t) => isFalsePass(t.outcome)),
            duplicates: rate(c, (t) => t.duplicates > 0),
          },
        ];
      }),
    ),
  ]),
);
fs.writeFileSync(path.join(runDir, "summary.json"), JSON.stringify(summary, null, 2));
process.stdout.write(md);
